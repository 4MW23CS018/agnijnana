def normalize_label(label):

    text = str(
        label
    ).strip().lower()

    text = re.sub(
        r"[^a-z0-9]+",
        "_",
        text
    )

    text = re.sub(
        r"_+",
        "_",
        text
    ).strip("_")

    mapping = {

        # ----------------------
        # Core visible defects
        # ----------------------

        "crack":
            "crack",

        "scratch":
            "scratch",

        "bent_rim":
            "bent_rim",

        # ----------------------
        # Surface defects
        # ----------------------

        "paint_damage":
            "paint_damage",

        "alloy_paint_removal":
            "paint_damage",

        "paint_removal":
            "paint_damage",

        "alloy_chip":
            "chip",

        "chip":
            "chip",

        "alloy_corrosion":
            "corrosion",

        "corrosion":
            "corrosion",

        "alloy_buckle":
            "buckle",

        "buckle":
            "buckle",

        "alloy_scuff":
            "scuff",

        "alloy_scuff_severe":
            "scuff_severe",

        # ----------------------
        # Manufacturing defects
        # ----------------------

        "blow_hole":
            "blow_hole",

        "blowhole":
            "blow_hole",

        "incomplete_welding":
            "incomplete_welding",

        "incomplete_weld":
            "incomplete_welding",

        "prosity_weld":
            "porosity",

        "porosity_weld":
            "porosity",

        "porosity":
            "porosity",

        "prosity_incomplete_blowhole":
            "mixed_porosity_blowhole",

        # ----------------------
        # Object class
        # NOT a defect
        # ----------------------

        "alloy_wheel":
            "IGNORE"
    }

    return mapping.get(
        text,
        "IGNORE"
    )


