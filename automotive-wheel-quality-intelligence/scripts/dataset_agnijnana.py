# Convert segmentation polygons into YOLO bounding boxes

def polygon_to_bbox(
    coordinates
):

    xs = coordinates[
        0::2
    ]

    ys = coordinates[
        1::2
    ]

    x_min = min(xs)
    x_max = max(xs)

    y_min = min(ys)
    y_max = max(ys)

    x_center = (
        x_min + x_max
    ) / 2

    y_center = (
        y_min + y_max
    ) / 2

    width = (
        x_max - x_min
    )

    height = (
        y_max - y_min
    )

    return [
        x_center,
        y_center,
        width,
        height
    ]

