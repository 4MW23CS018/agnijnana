# Union-Find structure
parent = list(
    range(n)
)

def find(x):

    while parent[x] != x:

        parent[x] = parent[
            parent[x]
        ]

        x = parent[x]

    return x


def union(a, b):

    root_a = find(a)
    root_b = find(b)

    if root_a != root_b:

        parent[root_b] = root_a


def phash_distance(hash1, hash2):

    if (
        hash1 is None
        or
        hash2 is None
    ):
        return 999

    try:

        return (
            int(hash1, 16)
            ^
            int(hash2, 16)
        ).bit_count()

    except Exception:

        return 999


