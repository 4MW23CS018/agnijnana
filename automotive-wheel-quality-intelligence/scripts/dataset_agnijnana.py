# Build image index with correct YOLO image/label pairing

IMAGE_EXTENSIONS = {
    ".jpg",
    ".jpeg",
    ".png",
    ".bmp",
    ".webp"
}

image_records = []

for dataset_name in classes_df["dataset"].unique():

    dataset_dir = RAW_DIR / dataset_name

    if not dataset_dir.exists():
        continue

    # Find every image anywhere inside the dataset
    for image_path in dataset_dir.rglob("*"):

        if not image_path.is_file():
            continue

        if image_path.suffix.lower() not in IMAGE_EXTENSIONS:
            continue

        # ------------------------------------------------
        # Find corresponding label
        #
        # Roboflow structure:
        #
        # train/images/example.jpg
        # train/labels/example.txt
        #
        # valid/images/example.jpg
        # valid/labels/example.txt
        # ------------------------------------------------

        parts = image_path.parts

        label_path = None

        if "images" in parts:

            # Replace the LAST "images" directory with "labels"
            parts_list = list(parts)

            image_folder_index = (
                len(parts_list)
                - 1
                - parts_list[::-1].index("images")
            )

            parts_list[image_folder_index] = "labels"

            candidate = Path(*parts_list).with_suffix(".txt")

            if candidate.exists():
                label_path = candidate

        # ------------------------------------------------
        # Fallback:
        # search for same filename inside labels/
        # ------------------------------------------------

        if label_path is None:

            possible_labels = list(
                dataset_dir.rglob(
                    image_path.stem + ".txt"
                )
            )

            label_candidates = [
                p for p in possible_labels
                if "labels" in p.parts
            ]

            if label_candidates:
                label_path = label_candidates[0]

        image_records.append({

            "dataset":
                dataset_name,

            "image_path":
                str(image_path),

            "label_path":
                str(label_path)
                if label_path is not None
                else "",

            "has_label":
                label_path is not None
        })


