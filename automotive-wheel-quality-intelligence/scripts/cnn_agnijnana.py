names = ["bent_rim", "crack", "scratch"]

for split in ["train"]:
    image_dir = LOCAL_SEG_DATASET / "images" / split
    label_dir = LOCAL_SEG_DATASET / "labels" / split

    print("\n" + "=" * 70)
    print(f"VISUAL QA — {split.upper()}")
    print("=" * 70)

    image_files = list(image_dir.glob("*"))

    for cls_id, cls_name in enumerate(names):

        candidates = []

        for img_path in image_files:
            label_path = label_dir / f"{img_path.stem}.txt"

            if not label_path.exists():
                continue

            text = label_path.read_text().strip()

            if not text:
                continue

            for line in text.splitlines():
                parts = line.split()

                if len(parts) < 7:
                    continue

                if int(parts[0]) == cls_id:
                    candidates.append(img_path)
                    break

        print(f"{cls_name}: {len(candidates)} candidate images")

        if not candidates:
            continue

        sample = random.sample(
            candidates,
            min(3, len(candidates))
        )

        for img_path in sample:

            img = cv2.imread(str(img_path))
            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

            h, w = img.shape[:2]

            label_path = label_dir / f"{img_path.stem}.txt"

            plt.figure(figsize=(7, 7))
            plt.imshow(img)

            for line in label_path.read_text().strip().splitlines():
                parts = line.split()

                if len(parts) < 7:
                    continue

                cid = int(parts[0])

                if cid != cls_id:
                    continue

                coords = np.array(
                    list(map(float, parts[1:])),
                    dtype=np.float32
                ).reshape(-1, 2)

                coords[:, 0] *= w
                coords[:, 1] *= h

                polygon = np.vstack([coords, coords[0]])

                plt.plot(
                    polygon[:, 0],
                    polygon[:, 1],
                    linewidth=2
                )

            plt.title(f"{cls_name} — {img_path.name}")
            plt.axis("off")
            plt.show()

